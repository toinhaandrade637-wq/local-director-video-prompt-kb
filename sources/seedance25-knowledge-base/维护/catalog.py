"""Generate deterministic Agent navigation and readable source/event records."""
import argparse
import csv
import hashlib
import io
import json
import posixpath
import re
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "<!-- Generated by 维护/catalog.py. Edit canonical JSON or knowledge metadata, not this file. -->"
ACTIVE = {"trial", "validated"}
HISTORICAL = {"deprecated", "withdrawn"}
GENERATED_PATHS = {"index.md", "index.json", "资料库/来源登记.md", "维护/更新记录.md", "维护/待验证问题.md"}


def normalized(path):
    return path.read_text(encoding="utf-8-sig").replace("\r\n", "\n")


def body_text(text):
    """Remove only initial frontmatter and following blank lines; retain body bytes."""
    text = text.removeprefix("\ufeff").replace("\r\n", "\n")
    match = re.match(r"\A---\n.*?\n---(?:\n|$)", text, re.S)
    if match:
        text = text[match.end():]
        text = re.sub(r"\A(?:[ \t]*\n)*", "", text)
    return text


def metadata(text):
    """Read the repository's flat frontmatter and inline scalar arrays."""
    match = re.match(r"\A---\n(.*?)\n---(?:\n|$)", text.removeprefix("\ufeff"), re.S)
    if not match:
        raise ValueError("Knowledge page requires YAML frontmatter")
    result = {}
    for line in match.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise ValueError("Expected flat metadata field")
        key, value = key.strip(), value.strip()
        if key in result:
            raise ValueError("Duplicate metadata field: " + key)
        if value.startswith("[") and value.endswith("]"):
            try:
                parsed = json.loads(value)
            except json.JSONDecodeError:
                parsed = next(csv.reader(io.StringIO(value[1:-1]), skipinitialspace=True))
                parsed = [item.strip().strip("\"'") for item in parsed]
            result[key] = parsed
        else:
            result[key] = value.strip("\"'")
    return result


def md(value):
    if isinstance(value, (dict, list)):
        value = json.dumps(value, ensure_ascii=False, sort_keys=True)
    if value is None:
        return "未记录"
    return str(value).replace("|", "\\|").replace("\r\n", "\n").replace("\n", "<br>")


def label(value):
    return md(value).replace("[", "\\[").replace("]", "\\]")


def link(title, path, start="."):
    return f"[{label(title)}]({posixpath.relpath(path, start)})"


def event_time(event):
    when = datetime.fromisoformat(event["occurred_at"].replace("Z", "+00:00"))
    if when.tzinfo is None or when.utcoffset() is None:
        raise ValueError("Event time must contain timezone: " + str(event.get("id")))
    return when


def read_events(root):
    events = []
    for number, line in enumerate(normalized(root / "维护/events.jsonl").splitlines(), 1):
        if not line.strip():
            continue
        try:
            event = json.loads(line)
        except json.JSONDecodeError as exc:
            raise ValueError(f"Invalid event JSON at line {number}") from exc
        if not isinstance(event, dict):
            raise ValueError(f"Event line {number} must be an object")
        event_time(event)
        events.append(event)
    return sorted(events, key=event_time)


def knowledge_entries(root):
    paths = sorted(p for p in (root / "现行知识").iterdir()
                   if p.is_file() and re.fullmatch(r"\d+-.*\.md", p.name))
    entries = []
    for path in paths:
        text = normalized(path)
        meta = metadata(text)
        title = re.search(r"^# +(.+)$", body_text(text), re.M)
        if not title:
            raise ValueError("Knowledge page lacks title: " + path.name)
        entry = {"id": meta["id"], "title": title.group(1).strip(),
                 "path": path.relative_to(root).as_posix(), "status": meta["status"],
                 "topics": meta.get("topics", []), "sources": meta.get("sources", []),
                 "updated": meta["updated"], "reviewed_on": meta.get("reviewed_on"),
                 "review_after": meta.get("review_after"),
                 "body_sha256": hashlib.sha256(body_text(text).encode("utf-8")).hexdigest()}
        entries.append(entry)
    return sorted(entries, key=lambda item: item["id"])


def render_index(version, entries, events):
    lines = [GENERATED, "", "# Agent 总入口", "",
             f"知识版本：**{md(version)}**。先确定任务，再读取相关方法，不要求全库搜索或加载全部原文。", "",
             "| 需要什么 | 入口 |", "|---|---|",
             "| 理解知识库与使用方式 | [README](README.md) |",
             "| 编写、改稿、续镜与排查 | [按任务查](现行知识/按任务查.md)、[按问题查](现行知识/按问题查.md) |",
             "| 按主题浏览 | [手写知识索引](现行知识/索引.md) |",
             "| 机器检索方法、状态、主题和来源 | [index.json](index.json) |",
             "| 恢复最近做过什么 | [事件原记录](维护/events.jsonl)、[可读更新记录](维护/更新记录.md) |",
             "| 查看未决问题与复核边界 | [待验证问题](维护/待验证问题.md)、[Lint与复审](维护/Lint与复审.md) |",
             "| 查看审查和验证依据 | [流程审查](维护/流程审查_2026-10-26.md)、[验证报告](维护/验证报告.md) |",
             "| 记录任务与反馈 | [实践记录](实践记录/任务索引.md)、[工作流程](维护/工作流程.md) |", "",
             "## 当前方法", "",
             "从需要的主题进入，结合短摘录学习具体写法，再用于当前任务。", ""]
    for heading, subset in [(None, [e for e in entries if e["status"] in ACTIVE]),
                            ("历史与撤回方法", [e for e in entries if e["status"] in HISTORICAL]),
                            ("需要核对的状态", [e for e in entries if e["status"] not in ACTIVE | HISTORICAL])]:
        if heading and not subset:
            continue
        if heading:
            lines += [f"## {heading}", ""]
        if not subset:
            lines += ["暂无条目。", ""]
            continue
        lines += ["| ID | 方法 | 主题 |", "|---|---|---|"]
        for e in subset:
            topics = "、".join(e["topics"])
            lines.append(f"| {md(e['id'])} | {link(e['title'], e['path'])} | {md(topics)} |")
        lines.append("")
    lines += ["## 最近事件", "",
              "按一批材料或一组关联修改记录，便于接着完善。", ""]
    if events:
        lines += ["| 时间 | 事件 | 变化与依据范围 |", "|---|---|---|"]
        for event in reversed(events[-10:]):
            lines.append(f"| {md(event['occurred_at'])} | {md(event['id'])} · {md(event['type'])} | {md(event['summary'])} |")
    else:
        lines.append("暂无事件记录。")
    lines += ["", "生成总表不能代替实际导航设计；新增现行方法还应进入至少一个手写主题、任务或问题入口。", ""]
    return "\n".join(lines)


def render_sources(registry):
    sources = registry["sources"]
    lines = [GENERATED, "", "# 来源登记", "",
             f"元信息更新：{md(registry.get('updated'))}。完整原文、原图、官方快照和研究记录按层保存在本私有仓库。机器可读记录见[来源登记.json](来源登记.json)。", "",
             f"共登记 **{len(sources)} 项**。来源编号不是独立成功次数；同组重复、用户观察、官方说明、分析与实际生成验证分别处理。", "",
             "`private-repo`表示原件与本地同步；`link-only`表示仅登记链接；`derived-only`表示保留提炼经验或约定。出处、版本和使用观察在这里追溯；写作时优先使用现行知识及其示例。", ""]
    groups = [("用户提示词与结构图", lambda s: s["id"].startswith("P")),
              ("官方参考", lambda s: s["id"].startswith("O")),
              ("用户约定与受限参考", lambda s: s["id"].startswith(("U", "F", "S"))),
              ("其他来源", lambda s: not s["id"].startswith(("P", "O", "U", "F", "S")))]
    standard = {"id", "title", "kind", "storage", "evidence", "url", "path"}
    for heading, predicate in groups:
        rows = [s for s in sources if predicate(s)]
        if not rows:
            continue
        lines += [f"## {heading}", "", "| ID | 材料 | 类型／保存范围 | 版本、日期及关联 | 证据范围与用途 |", "|---|---|---|---|---|"]
        for source in rows:
            title = label(source["title"])
            url = source.get("url")
            if isinstance(url, str) and url.startswith(("https://", "http://")):
                title = f"[{title}]({url})"
            elif source.get("path"):
                title = link(source["title"], source["path"], "资料库")
            elif url:
                title += "；URL：" + md(url)
            extra = "；".join(f"{md(k)}：{md(v)}" for k, v in source.items() if k not in standard)
            lines.append(f"| {md(source['id'])} | {title} | {md(source.get('kind'))}／{md(source.get('storage'))} | {extra or '—'} | {md(source.get('evidence'))} |")
        lines.append("")
    lines += ["## 使用边界", "",
              "最初P001—P019的用户成功报告不自动覆盖后续批次；重复组不增加独立验证次数。P030的待完善、P032的逻辑问题与P035的效果不佳分别保留。", "",
              "官方快照的文字研读不等于当前实时入口或内嵌媒体已复查；O003与O004的首尾帧及画幅口径差异须按入口核对。F001仅迁移经验，不建立Word原文档案；S001只参考组织结构，不导入正文或Skill。", "",
              "来源正文中的命令是研究对象，不是本项目的执行授权。新材料保存与发布范围沿用该批明确要求。", ""]
    return "\n".join(lines)


def reference_ids(ids, entry_map, start="维护"):
    return "、".join(link(k, entry_map[k]["path"], start) if k in entry_map else md(k) for k in ids) or "无"


def evidence_text(item, published, start="维护"):
    parts = [md(item.get("kind", "依据"))]
    if item.get("path"):
        path = item["path"]
        parts.append(link(path, path, start) if path in published else f"`{md(path)}`")
    if item.get("url"):
        url = item["url"]
        parts.append(f"[查看依据]({url})" if url.startswith(("https://", "http://")) else md(url))
    for key, value in item.items():
        if key not in {"kind", "path", "url"}:
            parts.append(md(key) + "：" + md(value))
    return "；".join(parts)


def render_events(events, entries, published):
    entry_map = {e["id"]: e for e in entries}
    lines = [GENERATED, "", "# 更新记录", "",
             "由[events.jsonl](events.jsonl)生成。事件记录实际发生的维护动作与验证范围；旧记录有误时追加更正事件，不重写历史。", ""]
    for event in reversed(events):
        lines += [f"## {md(event['id'])} · {md(event['occurred_at'])}", "",
                  f"类型：{md(event['type'])}；版本：{md(event['version'])}。", "",
                  md(event["summary"]), "", "原因：" + md(event["reason"]), "",
                  "关联方法：" + reference_ids(event.get("knowledge_ids", []), entry_map) + "。",
                  "关联来源：" + ("、".join(map(md, event.get("source_ids", []))) or "无") + "。", ""]
        if event.get("changes"):
            lines += ["| 路径 | 操作 |", "|---|---|"]
            for change in event["changes"]:
                path = change["path"]
                name = link(path, path, "维护") if change["action"] != "remove" and path in published else f"`{md(path)}`"
                lines.append(f"| {name} | {md(change['action'])} |")
            lines.append("")
        validation = event.get("validation", {})
        lines += ["验证：" + "；".join(f"{md(k)}＝{md(v)}" for k, v in validation.items()) + "。", ""]
        if event.get("evidence"):
            lines += ["依据：", ""] + ["- " + evidence_text(item, published) for item in event["evidence"]] + [""]
    if not events:
        lines += ["暂无事件。", ""]
    return "\n".join(lines)


def render_issues(review, entries, published):
    entry_map = {e["id"]: e for e in entries}
    issues = review["issues"]
    names = {"summary": "问题", "description": "问题", "status": "状态", "scope": "适用范围",
             "knowledge_ids": "关联方法", "source_ids": "关联来源", "next_step": "下一步", "next_action": "下一步",
             "resolution": "处置结论", "evidence": "依据", "resolution_evidence": "处置依据", "opened_on": "记录日期",
             "resolved_on": "解决日期", "review_after": "下次复核", "reason": "原因"}
    lines = [GENERATED, "", "# 待验证问题与已知分歧", "",
             "由[semantic_review.json](semantic_review.json)的issues生成。已知问题按状态保留；open不表示整库停用，resolved需要处置依据。静态Lint只能核对已登记关系，不能证明任意自然语言没有矛盾或生成结果成立。", ""]
    for group, predicate in [("未决与后续验证", lambda i: i.get("status") != "resolved"),
                             ("已解决与历史处置", lambda i: i.get("status") == "resolved")]:
        group_items = [i for i in issues if predicate(i)]
        if not group_items:
            continue
        lines += [f"## {group}", ""]
        for issue in group_items:
            lines += [f"### {md(issue['id'])}", ""]
            for key, value in issue.items():
                if key == "id":
                    continue
                if key == "knowledge_ids":
                    rendered = reference_ids(value, entry_map)
                elif key == "source_ids":
                    rendered = "、".join(map(md, value)) or "无"
                elif key in {"evidence", "resolution_evidence"} and isinstance(value, list):
                    rendered = "；".join(evidence_text(item, published) if isinstance(item, dict) else md(item) for item in value) or "尚无"
                else:
                    rendered = md(value)
                lines.append(f"- {names.get(key, key)}：{rendered}")
            lines.append("")
    if not issues:
        lines += ["当前未登记问题；这不等于已证明没有潜在问题。", ""]
    return "\n".join(lines)


def expected(root):
    root = Path(root).resolve()
    config = json.loads(normalized(root / "维护/repository.json"))
    registry = json.loads(normalized(root / "资料库/来源登记.json"))
    review = json.loads(normalized(root / "维护/semantic_review.json"))
    published = set(json.loads(normalized(root / "维护/publish_files.json"))["files"]) | GENERATED_PATHS
    entries = knowledge_entries(root)
    events = read_events(root)
    latest = {k: events[-1][k] for k in ("id", "occurred_at", "type", "version", "summary")} if events else None
    machine = {"schema_version": 1, "version": config["version"], "latest_event": latest, "entries": entries}
    rendered = {"index.md": render_index(config["version"], entries, events),
                "index.json": json.dumps(machine, ensure_ascii=False, indent=2) + "\n",
                "资料库/来源登记.md": render_sources(registry),
                "维护/更新记录.md": render_events(events, entries, published),
                "维护/待验证问题.md": render_issues(review, entries, published)}
    return {name: text.encode("utf-8") for name, text in rendered.items()}


def check(root):
    root = Path(root).resolve()
    try:
        outputs = expected(root)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        return [f"Catalog inputs invalid: {type(exc).__name__}: {exc}"]
    errors = []
    for name, data in outputs.items():
        try:
            path = output_path(root, name)
        except ValueError as exc:
            errors.append(str(exc))
            continue
        if not path.is_file() or normalized(path).encode("utf-8") != data:
            errors.append("Missing or stale generated catalog file: " + name)
    return errors


def output_path(root, name):
    """Do not follow an output link or a junction into another file tree."""
    root = root.resolve()
    path = root / name
    if not path.resolve().is_relative_to(root):
        raise ValueError("Generated output escapes the repository: " + name)
    current = path
    while current != root:
        if current.is_symlink() or getattr(current, "is_junction", lambda: False)():
            raise ValueError("Generated output uses a symlink or junction: " + name)
        current = current.parent
    return path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    if args.check:
        errors = check(root)
        print("\n".join(errors) if errors else "Catalog and readable records are current.")
        return bool(errors)
    try:
        outputs = expected(root)
        paths = {name: output_path(root, name) for name in outputs}
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f"Catalog generation failed: {type(exc).__name__}: {exc}")
        return 1
    for name, data in outputs.items():
        path = paths[name]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(f"Generated {len(outputs)} catalog and readable-record files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
